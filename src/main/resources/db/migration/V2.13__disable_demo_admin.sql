-- V1.002 засеял демо-аккаунт admin_mail с ролью ADMIN (#45). Войти под ним нельзя — SSO такого
-- адреса не выдаёт, — но правило последнего администратора его считало, и последний настоящий
-- организатор мог снять роль с себя: в админку стало бы некому войти.
--
-- Выключаем, а не понижаем: правило теперь считает только включённых, а роль на аккаунте служит
-- административной фикстурой тестам и проверкам роли в сервисах. По почте, а не по id 1 — в
-- существующей базе id не обязан совпадать с сидом.
UPDATE users SET is_enabled = false WHERE lower(email) = 'admin_mail';
