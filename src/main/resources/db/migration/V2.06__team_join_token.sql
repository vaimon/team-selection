-- Ссылка-приглашение в команду (#13). Токен живёт на самой команде: NULL значит, что ссылки нет —
-- либо её ещё не выпускали, либо тимлид её отключил. Отключённая ссылка не оживает, выпускается новая.
ALTER TABLE teams
    ADD COLUMN join_token varchar(64);

-- Поиск команды идёт по токену, и два одинаковых токена означали бы неоднозначную ссылку.
CREATE UNIQUE INDEX teams_join_token_unique ON teams (join_token);
