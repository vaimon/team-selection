package ru.sfedu.teamselection.enums;

/**
 * Почему действие отклонено ответом 409. Фронт по коду решает, что предложить: повторить с явным
 * флагом, выбрать преемника, обновить данные или отправить в кабинет ПД.
 */
public enum ConflictReason {
    /** Команда уже набрала цель по курсу студента; повторить можно с явным allowOverTarget. */
    OVER_TARGET,
    /** Перемещается тимлид: нужно назначить преемника, а если он последний участник — распустить команду. */
    LEAD_NEEDS_SUCCESSOR,
    /** Команду успели изменить после того, как доска была загружена; доску нужно обновить. */
    STALE_VERSION,
    /** Состав набора передан в кабинет ПД, здесь он только для чтения (#15). */
    HANDED_OVER
}
