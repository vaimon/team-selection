package ru.sfedu.teamselection.enums;

/**
 * Почему конкретный человек не может войти в команду по ссылке. Фронт по коду решает, что показать
 * и куда вести: анкета, другой набор, поиск другой команды.
 */
public enum JoinRefusalReason {
    /** Не заполнил анкету текущего набора — участником он ещё не стал. */
    NOT_A_PARTICIPANT,
    /** Анкета есть, но в другом наборе: команда и студент из разных наборов. */
    ANOTHER_SELECTION,
    /** Уже состоит в этой же команде. */
    ALREADY_IN_THIS_TEAM,
    /** Уже состоит в другой команде. */
    ALREADY_IN_A_TEAM,
    /** Мест для его курса в команде не осталось. */
    NO_PLACES_FOR_THE_YEAR,
    /** Набор ещё не открыт или уже закрыт. */
    WINDOW_CLOSED
}
